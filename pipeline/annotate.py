#!/usr/bin/env python3
"""Validate a hand-written tie table and build ST_ties.json / TT_ties.json.

The tie table is Python written by the analyst (never generated by regex or a
word list).  Row format (13 fields)::

    (sent, text, cat, sub, ante, conf, alt, note, occ,
     gap_after, recovered, level, ref)

- text tie: text is the exact substring in the sentence; gap_after/recovered
  are None.
- ellipsis: text=None; gap_after is an exact substring ending immediately before
  the zero slot; recovered is the meaning in ``{...}``.  Use gap_after='' for a
  sentence-initial gap.
- level: 'LC' (intersentential), 'TC' (intra-sentential), 'TD' (title).
- ref: required for R ties and must be A/C/E; None for all other categories.
  This script never invents a default reference direction.

The manual analysis gate: by default the pair's analysis markdown must exist in
work/analysis/ and contain at least six numbered sections.  Use
``--allow-missing-analysis`` only for a smoke test with dummy data.
"""
from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from collections import Counter
from pathlib import Path

from .common import dump_json, load_json, pair_dir

ROW_FIELDS = 13


def analysis_path(work: Path, pid: str) -> Path | None:
    root = work / "analysis"
    if not root.is_dir():
        return None
    hits = sorted(root.glob(f"{pid}*.md"))
    return hits[0] if hits else None


def check_analysis(work: Path, pid: str) -> tuple[bool, str]:
    p = analysis_path(work, pid)
    if not p:
        return False, f"missing work/analysis/{pid}*.md"
    text = p.read_text(encoding="utf-8")
    heads = len(re.findall(r"^##\s+\d", text, flags=re.M))
    if len(text) < 600 or heads < 6:
        return False, (f"{p.name} is too short ({len(text)} chars, {heads} "
                       f"numbered sections); complete the 9-section template first")
    return True, str(p)


def load_table(path: Path):
    spec = importlib.util.spec_from_file_location(f"tie_{path.stem}", path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load tie table: {path}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return getattr(mod, "ST"), getattr(mod, "TT")


def parse_row(raw, n: int, pid: str, side: str):
    if len(raw) < 9:
        raise SystemExit(f"{pid}-{side}-{n:03d}: row has {len(raw)} fields, need 9+")
    (sent, text, cat, sub, ante, conf, alt, note, occ) = raw[:9]
    gap_after = raw[9] if len(raw) > 9 else None
    recovered = raw[10] if len(raw) > 10 else None
    level = raw[11] if len(raw) > 11 and raw[11] else "LC"
    ref = raw[12] if len(raw) > 12 and raw[12] else None
    if cat not in {"R", "S", "E", "C", "L"}:
        raise SystemExit(f"{pid} {side} row {n}: invalid cat {cat!r}")
    if level not in {"LC", "TC", "TD"}:
        raise SystemExit(f"{pid} {side} row {n}: invalid level {level!r}")
    if cat == "R" and ref not in {"A", "C", "E"}:
        raise SystemExit(
            f"{pid} {side} row {n}: R tie needs ref='A'/'C'/'E' (manual decision); "
            f"got {ref!r}")
    if cat != "R" and ref:
        raise SystemExit(f"{pid} {side} row {n}: ref is only valid for R")
    if text is None:
        if gap_after is None or recovered is None:
            raise SystemExit(
                f"{pid} {side} row {n}: E tie needs gap_after and recovered")
    else:
        if gap_after is not None or recovered is not None:
            raise SystemExit(
                f"{pid} {side} row {n}: text tie must leave gap_after/recovered None")
    return {
        "sent": sent, "text": text, "cat": cat, "sub": sub,
        "ante": ante, "conf": conf, "alt": alt, "note": note,
        "occ": occ, "gap_after": gap_after, "recovered": recovered,
        "level": level, "ref": ref,
    }


def build_side(work: Path, pid: str, side: str, pref: str, table, n_start=1):
    d = pair_dir(work, pid)
    seg = load_json(d / f"{pref}_seg.json")
    sents = {s["id"]: s for s in seg["sentences"]}
    ties, errors = [], []
    for n, raw in enumerate(table, 1):
        try:
            row = parse_row(raw, n, pid, side)
        except SystemExit as e:
            errors.append(str(e))
            continue
        s = sents.get(row["sent"])
        if not s:
            errors.append(f'{pid}-{side}-{n:03d}: sentence {row["sent"]} not found')
            continue
        text = s["text"]
        tid = f'{pid}-{side}-{len(ties) + 1:03d}'
        if row["text"] is None:
            gap = row["gap_after"]
            occ = row["occ"] or 1
            pos, found = -1, 0
            p = -1
            while True:
                p = text.find(gap, p + 1)
                if p < 0:
                    break
                found += 1
                if found == occ:
                    pos = p + len(gap)
                    break
            if pos < 0:
                errors.append(f'{tid}: gap_after {gap!r} occ {occ} not found in {row["sent"]}')
                continue
            tie = {"id": tid, "sent": row["sent"], "text": None, "occ": occ,
                   "gap_after": gap, "recovered": row["recovered"],
                   "cat": row["cat"], "sub": row["sub"], "dir":
                   "cata" if row["ref"] == "C" else "ana",
                   "level": row["level"], "ante": row["ante"],
                   "conf": row["conf"], "alt": row["alt"], "note": row["note"]}
            if row["ref"]:
                tie["ref"] = row["ref"]
            ties.append(tie)
            continue

        t = row["text"]
        count = text.count(t)
        if count == 0:
            errors.append(f'{tid}: text {t!r} not found in {row["sent"]}: {text[:70]!r}')
            continue
        occ = row["occ"]
        if occ is None:
            if count > 1:
                errors.append(
                    f'{tid}: text {t!r} occurs {count}x in {row["sent"]}; '
                    f'set occ explicitly (1..{count})')
                continue
            occ = 1
        pos, found = -1, 0
        p = -1
        while True:
            p = text.find(t, p + 1)
            if p < 0:
                break
            found += 1
            if found == occ:
                pos = p
                break
        if pos < 0:
            errors.append(f'{tid}: occurrence {occ} of {t!r} not found in {row["sent"]}')
            continue
        tie = {"id": tid, "sent": row["sent"], "text": t, "occ": occ,
               "cat": row["cat"], "sub": row["sub"],
               "dir": "cata" if row["ref"] == "C" else "ana",
               "level": row["level"], "ante": row["ante"],
               "conf": row["conf"], "alt": row["alt"], "note": row["note"]}
        if row["ref"]:
            tie["ref"] = row["ref"]
        ties.append(tie)

    if errors:
        print(f"== {pid} {side}: {len(errors)} ERRORS ==", file=sys.stderr)
        for e in errors:
            print("  " + e, file=sys.stderr)
        return None
    dump_json(d / f"{pref}_ties.json", {"pair": pid, "lang": side, "ties": ties})
    c = Counter(t["cat"] for t in ties)
    print(f"{pid} {side}: {len(ties)} ties | {dict(sorted(c.items()))}")
    return ties


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Build tie JSON from a hand-written table")
    ap.add_argument("--work", default="work")
    ap.add_argument("--pair", required=True)
    ap.add_argument("--allow-missing-analysis", action="store_true")
    args = ap.parse_args(argv)

    work = Path(args.work)
    pid = args.pair
    if not args.allow_missing_analysis:
        ok, msg = check_analysis(work, pid)
        if not ok:
            print("ANALYSIS GATE FAILED: " + msg, file=sys.stderr)
            print("Write the manual analysis first (templates/analysis_template.md).",
                  file=sys.stderr)
            return 2
        print(f"analysis gate: OK ({msg})")

    table_path = work / "tie_tables" / f"{pid}.py"
    if not table_path.exists():
        print(f"ERROR: missing {table_path}", file=sys.stderr)
        return 2
    st, tt = load_table(table_path)
    if build_side(work, pid, "EN", "ST", st) is None:
        return 1
    if build_side(work, pid, "VI", "TT", tt) is None:
        return 1
    print(f"Next: python -m pipeline.render --work {work} --pair {pid}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
